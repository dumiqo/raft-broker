namespace RaftBroker.Storage.Log;

/// <summary>
/// Тип записи журнала - поле <c>recordType</c> фрейма.
/// </summary>
/// <remarks>
/// Таблица закрыта: значения закреплены навсегда, номера не переиспользуются, а неизвестный
/// тип при чтении - это порча, а не повод пропустить запись (см. <c>docs/formats/log-segment.md</c>,
/// §6 и §10). Значение <c>0x00</c> не занято специально: оно ловит обнулённые байты как ошибку.
/// </remarks>
public enum LogRecordType : byte
{
    /// <summary>Команда state machine: непрозрачные для хранилища байты.</summary>
    Command = 0x01,

    /// <summary>Пустая запись лидера, которой открывается новый терм. Payload обязан быть пустым.</summary>
    Noop = 0x02,

    /// <summary>Команда изменения состава кластера: тоже непрозрачные байты.</summary>
    Config = 0x03,
}
