namespace RaftBroker.Storage.Log;

/// <summary>
/// Итог одного прохода по сегменту: байты разобраны до конца или разбор остановился на хвосте.
/// </summary>
/// <remarks>
/// Значений намеренно два, и ни одно из них не называется "порча" или "обрыв". Отличить torn
/// write от порчи в середине можно только пробой продолжения (<c>docs/formats/log-segment.md</c>,
/// §9.5 шаг 5), а для неё нужно знать, запечатан ли сегмент: запечатанный обязан быть полон (§8),
/// последний - нет. Сегмент сам этого не знает, поэтому читатель сообщает факт "разбор
/// остановился", а решение принимает восстановление (<c>S1-T05</c>).
/// </remarks>
public enum SegmentScanStatus
{
    /// <summary>
    /// Все байты файла разобраны, последний фрейм кончился ровно на конце файла.
    /// </summary>
    /// <remarks>
    /// Пустой сегмент (только заголовок) тоже полон: фреймов ноль, разбор дошёл до конца файла.
    /// </remarks>
    Complete,

    /// <summary>
    /// Разбор остановился: на смещении <see cref="SegmentScanResult.ValidEndOffset"/> находится
    /// неполный или невалидный фрейм.
    /// </summary>
    /// <remarks>
    /// За <see cref="SegmentScanResult.ValidEndOffset"/> начинается хвост, судьбу которого решает
    /// восстановление: в последнем сегменте это кандидат в torn write (усечение), в запечатанном -
    /// порча (отказ). Читатель не усекает ничего сам.
    /// </remarks>
    TailProblem,
}
