namespace RaftBroker.Storage.Log;

/// <summary>
/// Политика долговечности: когда сегмент журнала вызывает fsync.
/// </summary>
/// <remarks>
/// <para>
/// Различие режимов - ровно в том, сколько записей покрывает один вызов fsync и что означает
/// возврат из <c>AppendAsync</c>. Решение владельца от 2026-09-28 и ADR
/// <c>docs/adr/0004-durability-policies.md</c>: режим по умолчанию - <see cref="GroupCommit"/>.
/// </para>
/// <para>
/// Ни один режим не отвечает клиенту до fsync в commit-пути Raft: подтверждённая запись обязана
/// пережить падение. <see cref="Periodic"/> этому требованию не удовлетворяет и потому для
/// commit-пути запрещён - он существует для объёмных, но не подтверждаемых записей; вызывающий
/// сам решает, когда вызвать явный fsync.
/// </para>
/// </remarks>
public enum DurabilityMode
{
    /// <summary>
    /// fsync после каждой записи. Эталонный режим для тестов долговечности: медленный,
    /// но самый простой для рассуждения - возврат из append означает "запись на устройстве".
    /// </summary>
    PerEntry = 1,

    /// <summary>
    /// fsync один раз на группу записей (один вызов append): несколько записей Raft,
    /// предложенных вместе, делят один fsync. Режим по умолчанию.
    /// </summary>
    GroupCommit = 2,

    /// <summary>
    /// fsync в append не вызывается вовсе: байты дописываются в файл, а на устройство их
    /// отправляет вызывающий явным <c>FlushToDiskAsync</c> по своему расписанию.
    /// Возврат из append не означает долговечность - для commit-пути режим запрещён.
    /// </summary>
    Periodic = 3,
}
