namespace RaftBroker.Storage.Log;

/// <summary>
/// Место сегмента в журнале по §8: запечатанный или последний.
/// </summary>
/// <remarks>
/// Различие решает восстановление (<c>S1-T05</c>): усекать оборванный хвост разрешено только
/// последнему сегменту, потому что запечатанный писатель fsync-нул перед созданием преемника
/// и оборванным быть не может. Какой сегмент последний, знает только каталог (<c>S1-T06</c>,
/// <c>S1-T07</c>), поэтому это знание передаётся восстановлению параметром: из одного файла его
/// не вывести, а угадывать нельзя - ошибка в сторону усечения теряет данные.
/// </remarks>
public enum SegmentKind
{
    /// <summary>Запечатанный: писатель закрыл его и создал преемника. Обязан быть полным до конца файла.</summary>
    Sealed,

    /// <summary>Последний: в него может идти запись. Только его хвост можно усечь.</summary>
    Last,
}
