namespace RaftBroker.Storage.Log;

/// <summary>
/// Статус разбора байтов сегмента: успех, нехватка байтов или обнаруженная порча.
/// </summary>
/// <remarks>
/// <see cref="Truncated"/> и <see cref="Corrupt"/> разделены намеренно: первое - это оборванная
/// запись в хвосте последнего сегмента (её можно отбросить), второе - порча, при которой
/// автоматическое усечение запрещено. Решение "усечь или отказать" принимает не кодек,
/// а восстановление (S1-T05), и принимает его по этим статусам.
/// </remarks>
public enum LogReadStatus
{
    /// <summary>Байты разобраны полностью, значение пригодно к использованию.</summary>
    Success,

    /// <summary>Данных не хватает: байты обрываются на середине структуры.</summary>
    Truncated,

    /// <summary>Данные есть целиком, но они нарушают формат.</summary>
    Corrupt,
}
