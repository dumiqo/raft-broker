namespace RaftBroker.Storage.IO;

/// <summary>
/// Открытый на чтение файл хранилища - читающая половина шва
/// <see cref="IStorageFileSystem"/>.
/// </summary>
/// <remarks>
/// <para>
/// Абстракция появилась в <c>S1-T04</c> по той же причине, что и пишущая: читатель сегмента
/// обязан сообщать, какие байты и по каким смещениям он просил, иначе тест на "сегмент читается
/// без полной загрузки в память" превращается в проверку комментария. Дубль из
/// <c>RaftBroker.TestKit</c> считает чтения и умеет возвращать меньше запрошенного, потому что
/// настоящий <see cref="System.IO.FileStream"/> вправе вернуть короткий результат, и цикл
/// дочитывания должен быть проверен, а не предполагаться.
/// </para>
/// <para>
/// Чтение адресуется смещением, а не позицией потока: у каждого открытого файла своя позиция,
/// и читатель, идущий назад, не должен влиять на того, кто читает вперёд. Потокобезопасность
/// не обещается: один открытый файл - один потребитель (та же модель, что у writer-actor
/// <c>S1-T08</c>).
/// </para>
/// </remarks>
public interface IStorageReadFile : IAsyncDisposable
{
    /// <summary>Путь файла: попадает в диагностику.</summary>
    string Path { get; }

    /// <summary>
    /// Длина файла на момент открытия, в байтах.
    /// </summary>
    /// <remarks>
    /// Снимок, а не текущее значение: читатели читают запечатанные сегменты, пока писатель
    /// работает с последним (§8 документа формата), поэтому "сегмент дочитан до EOF" обязано
    /// означать конец того файла, который читатель открыл, а не того, который дописали после.
    /// </remarks>
    long Length { get; }

    /// <summary>Читает байты по абсолютному смещению.</summary>
    /// <param name="offset">Смещение от начала файла; отрицательное запрещено.</param>
    /// <param name="destination">Буфер, в который читаются байты.</param>
    /// <param name="cancellationToken">Отмена до начала чтения.</param>
    /// <returns>
    /// Число прочитанных байт: не больше <paramref name="destination"/>.Length и не больше, чем
    /// осталось до конца файла. <c>0</c> означает конец файла (в том числе при
    /// <paramref name="offset"/> за его пределами). Короткий результат допустим: вызывающий
    /// обязан дочитывать в цикле, пока не получит нужное число байт или <c>0</c>.
    /// </returns>
    /// <exception cref="ArgumentOutOfRangeException">Смещение отрицательно.</exception>
    ValueTask<int> ReadAsync(long offset, Memory<byte> destination, CancellationToken cancellationToken);
}
